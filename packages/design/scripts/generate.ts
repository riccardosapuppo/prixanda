const GENERATED = "@generated by packages/design/scripts/generate.ts from packages/design/tokens.json: do not edit.";
const REGENERATE = "npm run design regenerates it; npm run design -- --check compares.";
const tsHeader = `// ${GENERATED}\n// ${REGENERATE}\n`;
const cssHeader = `/* ${GENERATED}\n   ${REGENERATE} */\n`;

function tokensCss(tokens: Tokens): string {
  const lines = [
    ...Object.entries(tokens.color).map(([name, value]) => `  --color-${name}: ${value};`),
    ...Object.entries(tokens.font).map(([name, value]) => `  --font-${name}: ${value};`),
    ...Object.entries(tokens.text).flatMap(([name, [size, leading]]) => [`  --text-${name}: ${size};`, `  --text-${name}--line-height: ${leading};`]),
    `  --spacing: ${tokens.spacing};`,
    ...Object.entries(tokens.radius).map(([name, value]) => `  --radius-${name}: ${value};`),
    ...Object.entries(tokens.breakpoint).map(([name, value]) => `  --breakpoint-${name}: ${value};`),
    ...Object.entries(tokens.ease).map(([name, value]) => `  --ease-${name}: ${value};`),
    ...Object.entries(tokens.duration).map(([name, value]) => `  --duration-${name}: ${value};`),
    ...Object.entries(tokens.shadow).map(([name, value]) => `  --shadow-${name}: ${value};`),
    ...Object.entries(tokens.weave).map(([name, value]) => `  --weave-${name}: ${value};`),
  ];
  return `${cssHeader}
/* Every token of the identity as a CSS variable. Pages with Tailwind import
   theme.css instead, which declares the same variables as its theme. */
:root {
${lines.join("\n")}
}
`;
}

function themeCss(tokens: Tokens): string {
  const themed = [
    // Tailwind's own palette, fonts, sizes, radii, shadows, curves and
    // breakpoints are cleared: only the identity's remain.
    "  --color-*: initial;",
    "  --font-*: initial;",
    "  --text-*: initial;",
    "  --radius-*: initial;",
    "  --shadow-*: initial;",
    "  --ease-*: initial;",
    "  --breakpoint-*: initial;",
    ...Object.entries(tokens.color).map(([name, value]) => `  --color-${name}: ${value};`),
    ...Object.entries(tokens.font).map(([name, value]) => `  --font-${name}: ${value};`),
    ...Object.entries(tokens.text).flatMap(([name, [size, leading]]) => [`  --text-${name}: ${size};`, `  --text-${name}--line-height: ${leading};`]),
    `  --spacing: ${tokens.spacing};`,
    ...Object.entries(tokens.radius).map(([name, value]) => `  --radius-${name}: ${value};`),
    ...Object.entries(tokens.breakpoint).map(([name, value]) => `  --breakpoint-${name}: ${value};`),
    ...Object.entries(tokens.ease).map(([name, value]) => `  --ease-${name}: ${value};`),
    ...Object.entries(tokens.shadow).map(([name, value]) => `  --shadow-${name}: ${value};`),
  ];
  const plain = [
    ...Object.entries(tokens.duration).map(([name, value]) => `  --duration-${name}: ${value};`),
    ...Object.entries(tokens.weave).map(([name, value]) => `  --weave-${name}: ${value};`),
  ];
  return `${cssHeader}
/* The identity as a Tailwind theme (v4): after @import "tailwindcss",
   @import "design/theme.css". Utilities come only from these tokens
   (bg-stone-0, text-ink-2, border-edge, text-sm, rounded-control...), and
   every variable is emitted, used or not, so plain CSS can read them too. */
@theme static {
${themed.join("\n")}
}

/* Tokens Tailwind has no utilities for: motion durations and the weaves
   (textures that say a state as well as its colour and its word). */
:root {
${plain.join("\n")}
}
`;
}

function tokensTs(tokens: Tokens): string {
  const ms = Object.fromEntries(Object.entries(tokens.duration).map(([name, value]) => [name, Number.parseInt(value, 10)]));
  return `${tsHeader}
/** The identity's colours, by token name. */
export const COLOR = ${JSON.stringify(tokens.color, null, 2)} as const;

export type ColorName = keyof typeof COLOR;

/** Foreground, background, the contrast they must reach, and where pages put them together. */
export const PAIRS: readonly (readonly [ColorName, ColorName, number, string])[] = ${JSON.stringify(tokens.pairs, null, 2)};

export const FONT = ${JSON.stringify(tokens.font, null, 2)} as const;

/** Type sizes: [font-size, line-height]. */
export const TEXT = ${JSON.stringify(tokens.text, null, 2)} as const;

export const EASE = ${JSON.stringify(tokens.ease, null, 2)} as const;

/** Motion durations in milliseconds: everything frequent stays under 300. */
export const DURATION_MS = ${JSON.stringify(ms, null, 2)} as const;
`;
}

async function iconsTs(): Promise<string> {
  const require = createRequire(join(root, "package.json"));
  let base: string;
  try {
    // The package exports no package.json: its main file sits in dist/.
    base = dirname(dirname(require.resolve("@phosphor-icons/core")));
  } catch {
    throw new Error("@phosphor-icons/core is not installed: npm install");
  }
  const version = (JSON.parse(await readFile(join(base, "package.json"), "utf8")) as { version: string }).version;
  const entries: string[] = [];
  for (const name of ICON_NAMES) {
    const svg = await readFile(join(base, "assets", "regular", `${name}.svg`), "utf8");
    const paths = [...svg.matchAll(/<path d="([^"]+)"\/>/g)].map((match) => match[1]);
    const elements = [...svg.matchAll(/<([a-z]+)\b/g)].map((match) => match[1]).filter((tag) => tag !== "svg" && tag !== "path");
    if (paths.length === 0 || elements.length > 0) throw new Error(`${name}.svg is not made of paths only; the icon set expects paths`);
    entries.push(`  ${JSON.stringify(name)}: ${JSON.stringify(paths)},`);
  }
  return `${tsHeader}
// Phosphor Icons, regular weight, from @phosphor-icons/core ${version}
// (MIT License, Copyright (c) 2023 Phosphor Icons: LICENSE-phosphor.txt beside
// this file). Each icon is drawn on a 256 by 256 grid in currentColor.

export const ICONS = {
${entries.join("\n")}
} as const satisfies Record<string, readonly string[]>;

export type IconName = keyof typeof ICONS;
`;
}

async function generate(): Promise<Map<string, string>> {
  const tokens = JSON.parse(await readFile(join(root, "tokens.json"), "utf8")) as Tokens;
  for (const [foreground, background] of tokens.pairs) {
    for (const name of [foreground, background]) {
      if (!(name in tokens.color)) throw new Error(`tokens.json: the pair ${foreground} on ${background} names an unknown colour ${name}`);
    }
  }
  return new Map([
    [join(root, "css", "tokens.css"), tokensCss(tokens)],
    [join(root, "css", "theme.css"), themeCss(tokens)],
    [join(root, "src", "tokens.ts"), tokensTs(tokens)],
    [join(root, "src", "icons.ts"), await iconsTs()],
  ]);
}

async function main(): Promise<number> {
  const check = process.argv.includes("--check");
  const files = await generate();
  if (check) {
    const stale: string[] = [];
    for (const [file, content] of files) {
      const current = existsSync(file) ? (await readFile(file, "utf8")).replaceAll("\r\n", "\n") : null;
      if (current !== content) stale.push(relative(root, file));
    }
    if (stale.length) {
      say(`out of date: ${stale.join(", ")}. npm run design regenerates them`);
      return 1;
    }
    say(`every generated file matches tokens.json and the icon list (${files.size} files)`);
    return 0;
  }
  for (const [file, content] of files) {
    await mkdir(dirname(file), { recursive: true });
    await writeFile(file, content);
  }
  say(`wrote ${[...files.keys()].map((file) => relative(root, file)).join(", ")}`);
  return 0;
}

process.exitCode = await main();
