// npm run design: what the two web applications share of the identity is
// written once, in tokens.json, and generated from it:
//   - css/tokens.css: every token as a CSS variable on :root, for any page;
//   - css/theme.css: the same tokens as a Tailwind theme, with Tailwind's own
//     colours, fonts, sizes, radii, shadows, curves and breakpoints cleared,
//     so a page cannot reach for a colour or a size the identity does not have;
//   - src/tokens.ts: the same values for TypeScript (tests, drawings);
//   - src/icons.ts: the icons the applications use, regular Phosphor (MIT),
//     copied from @phosphor-icons/core with the names below.
// The generated files are committed. `npm run design -- --check` generates in
// memory and fails when anything differs from what is committed.
import { existsSync } from "node:fs";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const say = (line: string) => console.log(`[design] ${line}`);

type Tokens = {
  color: Record<string, string>;
  pairs: [string, string, number, string][];
  font: Record<string, string>;
  text: Record<string, [string, string]>;
  spacing: string;
  radius: Record<string, string>;
  breakpoint: Record<string, string>;
  ease: Record<string, string>;
  duration: Record<string, string>;
  shadow: Record<string, string>;
  weave: Record<string, string>;
};

/** The icons the console and the site draw, by their Phosphor names. */
